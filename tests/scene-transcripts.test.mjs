import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {sceneTranscripts} from '../scripts/lib/scene-transcripts.mjs';
const hash = file => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
test('scene recognition reuses unchanged audio, invalidates model and rejects wrong assemblies or tampered evidence', t => {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'svm-asr-cache-'));
  t.after(() => fs.rmSync(folder, {recursive: true, force: true}));
  const ff = args => execFileSync('ffmpeg', ['-v', 'error', '-nostdin', '-y', ...args]);
  const a = path.join(folder, 'a.wav'), b = path.join(folder, 'b.wav'), c = path.join(folder, 'c.wav');
  [a,b,c].forEach((file,i) => ff(['-f','lavfi','-i',`sine=frequency=${400+i*200}:duration=1:sample_rate=48000`,'-c:a','pcm_s16le',file]));
  const joined = path.join(folder, 'joined.wav');
  const join = list => ff([...list.flatMap(f => ['-i', f]), '-filter_complex', list.map((_,i)=>`[${i}:a]`).join('')+`concat=n=${list.length}:v=0:a=1[out]`, '-map','[out]','-c:a','pcm_s16le',joined]);
  const model = path.join(folder, 'model.pt'); fs.writeFileSync(model,'fixture');
  let calls = 0;
  const transcribe = (file,out) => {calls++; fs.writeFileSync(out, JSON.stringify({audioSha256: hash(file), modelSha256: hash(model),text:path.basename(file),words:[{word:'one',start:.1,end:.8,probability:.99}]}));};
  const run = list => {join(list);return sceneTranscripts({segments:list.map(file=>({file,audioSha256:hash(file)})),audioFile:joined,audioSha256:hash(joined),model,language:'en',folder,transcribe});};
  const first = run([a,b]); assert.equal(calls,2); assert.equal(first.words[1].start,1.1);
  const second = run([a,c]); assert.equal(calls,3); assert.deepEqual(second.sceneCache.map(s=>s.reused),[true,false]);
  assert.deepEqual(run([c,a]).sceneCache.map(s=>s.reused),[true,true]); assert.equal(calls,3);
  fs.writeFileSync(model,'changed'); assert.deepEqual(run([a,c]).sceneCache.map(s=>s.reused),[false,false]);
  assert.throws(()=>sceneTranscripts({segments:[{file:b,audioSha256:hash(b)}],audioFile:joined,audioSha256:hash(joined),model,language:'en',folder,transcribe}),/exactly assemble/);
  const r=run([a,c]); const cached=path.join(folder,'scene-transcripts',`${r.sceneCache[0].key}.json`);fs.appendFileSync(cached,' ');
  assert.throws(()=>run([a,c]),/cache modified/);
});
